'''apply surface strain throughout the water column by multiplying the surface strain (i.e.) scaling it  
   at depth by a prescribed vertical profile inspired by the first baroclinic mode: 
   u_x(x,depth) = u_x(x,0) * F(d)'''
   
def vertical_profile_of_first_baroclinic_mode(depth_array,H_param,h_param):
    ''' This function generates the vertical structure that the u_x will be multiplied by to extended the dataset to depth.
        Inputs: depth_array: -z
                H_param: parameter of total ocean depth 
                h_param: controls how rapidly the profile changes with depth
        Returns vertical profile to multiply u_x too (outer product?)
    '''
    print(f'calculating vertical profile for: h_param = {h_param}, H_param = {H_param}')
    h = h_param * H_param
    # inside_cosine = 1 - (np.exp(-1 * depth_array / h)) / (1 - np.exp(-1 * H_param / h))
    inside_cosine = (1 - np.exp(-depth_array / h)) / (1 - np.exp(-H_param / h))
    F_d = 1 - 0.625 * (1 - np.cos(np.pi * inside_cosine)) # H = total ocean depth, h controls how rapidly the profile changes with depth, d = -z 
    return F_d

def plot_Fd_and_new_strain(F_d,depth_array,H_param,h_param,ds_copy_with_vertically_varying_strain):
    '''This function generates plots of the depth depending strain based on the first baroclinic mode.
       Inputs: F_d generated by calling function add_vertically_varying_strain_to_data(),
               depth array: dataset.depth 
               H_param: parameters of total ocean depth 
               h_param: controls how rapidly the profile changes with depth 
               ds_copy_with_vertically_varying_strain: dataset with vertically varying strain
    ''' 
    fig,axes = plt.subplots(1,2,figsize = (40,8))
    axes[0].plot(F_d,depth_array)
    axes[0].set_title(f'Vertical Profile of F(d) for H = {H_param}, h_over_H = {h_param}')
    axes[0].set_ylabel(f'Depth')
    axes[0].set_xlabel(f'F(d)')
    axes[0].invert_yaxis()

    axes[1].plot(ds_copy_with_vertically_varying_strain[f'strain_with_vertical_profile_H_{H_param}_h_over_H_{int(h_param * 1000)}'].isel(time = 0),depth_array)
    axes[1].set_title(f'Vertical Profile of Surface Strain * f(d) for H = {H_param}, h_over_H = {h_param}')
    axes[1].set_ylabel(f'Depth')
    axes[1].set_xlabel(f'F(d)')
    axes[1].invert_yaxis()
        
    plt.savefig(f'/Users/kat/Desktop/Seasonality_of_Vertical_Velocities/varying_strain_with_depth/figs_strain_depth_varying/strain_profile_for_H_is_{H_param}_and_h_over_H_is_{h_param}.png')
    plt.show()
    return None
    
def add_vertically_varying_strain_to_data(ds_original,H_params = [4000,4000,5500],h_over_H_params = [0.180, 0.574, 0.467]): 
    '''This function generates plots of the depth depending strain based on the first baroclinic mode.
       Inputs: F_d generated by calling function add_vertically_varying_strain_to_data(),
               depth array: dataset.depth 
               H_param: parameters of total ocean depth 
               h_param: controls how rapidly the profile changes with depth 
               ds_copy_with_vertically_varying_strain: dataset with vertically varying strain
    ''' 
    ds_copy_with_vertically_varying_strain = ds_original.copy()
    
    for idx in range(len(H_params)): 
        depth_array = ds_copy_with_vertically_varying_strain.depth
        H_param = H_params[idx]
        h_param = h_over_H_params[idx]
        F_d  = vertical_profile_of_first_baroclinic_mode(depth_array,H_param,h_param) 
        F_xarray = xr.DataArray(F_d, coords={"depth": depth_array}, dims="depth")
        strain = ds_copy_with_vertically_varying_strain['strain_neuro']
        # print(np.shape(strain))
        # print(np.shape(F_xarray))
        strain_with_vertical_profile_H__h_over_H__ = strain * F_xarray
        
        print(f'shape of strain with vertical profile {np.shape(strain_with_vertical_profile_H__h_over_H__)}')
        ds_copy_with_vertically_varying_strain[f'strain_with_vertical_profile_H_{int(H_params[idx])}_h_over_H_{int(h_over_H_params[idx] * 1000)}'] =  strain_with_vertical_profile_H__h_over_H__
        ds_copy_with_vertically_varying_strain[f'F_d_{H_params[idx]}_h_over_H_{int(h_over_H_params[idx] * 1000)}'] =  F_xarray
        # print((ds_copy_with_vertically_varying_strain[f'strain_with_vertical_profile_H_{int(H_params[idx])}_h_over_H_{int(h_over_H_params[idx] * 1000)}']))
        
        
    return ds_copy_with_vertically_varying_strain

    
    
